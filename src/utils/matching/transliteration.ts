/**
 * Компактная фонетическая транслитерация кириллица → латиница.
 *
 * Это НЕ строгий лингвистический стандарт (ГОСТ/BGN/ISO9) — задача не в
 * академической точности, а в том, чтобы после транслитерации fuzzy-сравнение
 * (см. jaroWinkler в textSimilarity.ts) само дотянуло оставшуюся разницу
 * в написании ("Даниел" vs "Даниэл" после транслитерации почти совпадают,
 * а не совпадают побайтово — этого достаточно).
 *
 * Покрывает стандартный русский алфавит + буквы, специфичные для
 * таджикской и узбекской кириллицы (ғ, қ, ҳ, ҷ, ӣ, ӯ, ў), так как каталог
 * товаров в приложении заполняется на ru/tg/uz.
 */
const CYRILLIC_TO_LATIN: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh',
  з: 'z', и: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'shch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
  // Расширенные буквы таджикской и узбекской кириллицы
  ғ: 'g', қ: 'q', ҳ: 'h', ҷ: 'j', ӣ: 'i', ӯ: 'u', ў: 'o',
};

/**
 * Транслитерирует кириллицу в латиницу посимвольно.
 * Латинские символы, цифры и пунктуация проходят без изменений — благодаря
 * этому смешанные строки вроде "рубашка Daniel" превращаются в
 * "rubashka daniel", а не ломаются на латинской части.
 */
export function cyrillicToLatin(input: string): string {
  let result = '';
  for (const ch of input.toLowerCase()) {
    result += CYRILLIC_TO_LATIN[ch] ?? ch;
  }
  return result;
}

/** true, если строка содержит хотя бы один кириллический символ. */
export function containsCyrillic(input: string): boolean {
  return /[\u0400-\u04FF]/.test(input);
}
